"""Typed boundaries; declarations never import native or model adapters."""
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Any, Protocol

from gccp_foundation.domain.errors import DispatchState
from gccp_foundation.domain.models import Action, JobPlan, QuotaKey, SnapshotRef


class Cancellation(Protocol):
    def is_cancelled(self) -> bool: ...


@dataclass(frozen=True)
class SessionContext:
    project_id: str
    session_id: str
    pid: int
    created_filetime: str
    hwnd: int
    project_file_id: str
    profile_id: str


@dataclass(frozen=True)
class OperationContext:
    session: SessionContext
    expected_snapshot: SnapshotRef
    deadline_monotonic: float
    cancellation: Cancellation


@dataclass(frozen=True)
class Observation:
    snapshot: SnapshotRef
    complete: bool
    scope: str
    data: Mapping[str, Any]
    evidence_ids: tuple[str, ...]


@dataclass(frozen=True)
class DispatchReceipt:
    action_id: str
    dispatch_state: DispatchState
    observation: Observation | None
    evidence_ids: tuple[str, ...]


class ProjectPort(Protocol):
    def inspect_environment(self, profile_id: str) -> Mapping[str, Any]: ...
    def open_workcopy(self, request: Mapping[str, Any], deadline: float, cancellation: Cancellation) -> SessionContext: ...
    def create_workcopy(self, request: Mapping[str, Any], deadline: float, cancellation: Cancellation) -> SessionContext: ...
    def bind(self, project_id: str, deadline: float, cancellation: Cancellation) -> SessionContext: ...
    def read_project(self, ctx: OperationContext, scopes: tuple[str, ...]) -> Observation: ...
    def save(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...
    def close_owned(self, ctx: OperationContext) -> DispatchReceipt: ...
    def reopen_owned(self, ctx: OperationContext) -> SessionContext: ...


class QuotaPort(Protocol):
    def search(self, ctx: OperationContext, key: QuotaKey) -> Observation: ...
    def read_candidates(self, ctx: OperationContext) -> Observation: ...
    def select_and_verify(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...
    def insert_and_verify(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...


class ResourcePort(Protocol):
    def read_resources(self, ctx: OperationContext) -> Observation: ...
    def edit_metadata_and_verify(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...
    def edit_price_and_recalculate(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...


class PricePort(Protocol):
    def export_native(self, ctx: OperationContext) -> Observation: ...
    def prepare_updates(self, ctx: OperationContext, action: Action) -> Observation: ...
    def inspect_preview(self, ctx: OperationContext, action: Action) -> Observation: ...
    def apply_import_once(self, ctx: OperationContext, action: Action) -> DispatchReceipt: ...
    def export_and_verify(self, ctx: OperationContext, action: Action) -> Observation: ...


class ReportPort(Protocol):
    def export_native(self, ctx: OperationContext, template_id: str) -> Observation: ...
    def read_bill(self, artifact_id: str) -> Observation: ...
    def verify_amount_scope(self, ctx: OperationContext, action: Action) -> Observation: ...


class EventPort(Protocol):
    def await_condition(self, ctx: OperationContext, predicate: Callable[[Observation], bool]) -> Observation: ...
    def invalidate_refs(self, session: SessionContext) -> None: ...


class StorePort(Protocol):
    def submit(self, plan: JobPlan) -> Mapping[str, Any]: ...
    def claim_project(self, project_id: str, job_id: str) -> None: ...
    def action_state(self, job_id: str, action_id: str) -> str: ...
    def action_observation(self, job_id: str, action_id: str) -> Observation: ...
    def begin_intent(self, job_id: str, action: Action, ctx: OperationContext,
                     preflight_evidence_ids: tuple[str, ...] = ()) -> str: ...
    def append_receipt(self, intent_id: str, receipt: DispatchReceipt) -> None: ...
    def checkpoint(self, job_id: str, state: Mapping[str, Any]) -> None: ...
    def load_pending(self, project_id: str) -> tuple[Mapping[str, Any], ...]: ...
    def read_evidence(self, artifact_id: str, project_id: str | None = None) -> Mapping[str, Any]: ...
